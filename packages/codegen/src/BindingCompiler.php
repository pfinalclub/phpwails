<?php

declare(strict_types=1);
namespace PhpWails\Codegen;

use PhpWails\Runtime\Attribute\Export;
use ReflectionClass;
use ReflectionMethod;
use ReflectionNamedType;
use ReflectionType;
use RuntimeException;

final class BindingCompiler
{
    public function compile(object $service, string $namespace = 'App'): array
    {
        $reflection = new ReflectionClass($service);
        $methods = [];
        foreach ($reflection->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
            $attributes = $method->getAttributes(Export::class);
            if ($attributes === []) continue;
            $attribute = $attributes[0]->newInstance();
            $name = $attribute->name ?? $method->getName();
            $parameters = [];
            foreach ($method->getParameters() as $parameter) {
                $parameters[] = ['name'=>$parameter->getName(), 'type'=>$this->typeName($parameter->getType()), 'optional'=>$parameter->isOptional()];
            }
            $methods[] = ['name'=>$namespace.'.'.$name, 'parameters'=>$parameters, 'returnType'=>$this->typeName($method->getReturnType())];
        }
        return ['schemaVersion'=>1,'namespace'=>$namespace,'methods'=>$methods];
    }

    public function write(array $manifest, string $outputDirectory): void
    {
        if (!is_dir($outputDirectory) && !mkdir($outputDirectory, 0777, true)) throw new RuntimeException('Unable to create binding output directory.');
        $this->atomic($outputDirectory.'/manifest.json', json_encode($manifest, JSON_PRETTY_PRINT|JSON_UNESCAPED_SLASHES|JSON_UNESCAPED_UNICODE).PHP_EOL);
        $namespace = $manifest['namespace'];
        $js = "// Generated by PhpWails; do not edit.\nconst invoke = globalThis.phpwails.invoke.bind(globalThis.phpwails);\nglobalThis.{$namespace} = {\n";
        foreach ($manifest['methods'] as $method) {
            $name = substr($method['name'], strlen($namespace) + 1);
            $params = array_map(static fn(array $p): string => $p['name'], $method['parameters']);
            $args = implode(', ', $params);
            $payload = $params === [] ? '{}' : '{'.implode(', ', array_map(static fn(string $p): string => $p.': '.$p, $params)).'}';
            $js .= "  {$name}: ({$args}) => invoke('{$method['name']}', {$payload}),\n";
        }
        $js .= "};\n";
        $this->atomic($outputDirectory.'/index.js', $js);
        $declarations = "// Generated by PhpWails; do not edit.\nexport declare const {$namespace}: {\n";
        foreach ($manifest['methods'] as $method) {
            $name = substr($method['name'], strlen($namespace) + 1);
            $params = implode(', ', array_map(static fn(array $p): string => $p['name'].($p['optional'] ? '?' : '').': '.self::tsType($p['type']), $method['parameters']));
            $declarations .= "  {$name}({$params}): Promise<".self::tsType($method['returnType']).">;\n";
        }
        $declarations .= "};\n";
        $this->atomic($outputDirectory.'/index.d.ts', $declarations);
    }

    private function typeName(?ReflectionType $type): string
    {
        if ($type === null) return 'mixed';
        if ($type instanceof ReflectionNamedType) return ($type->allowsNull() && $type->getName() !== 'mixed' ? '?' : '') . $type->getName();
        return 'mixed';
    }
    private static function tsType(string $type): string {
        return match (trim($type, '?')) { 'int','float' => 'number', 'bool' => 'boolean', 'string' => 'string', 'void' => 'void', default => str_starts_with($type, '?') ? 'unknown | null' : 'unknown' };
    }
    private function atomic(string $path, string $contents): void { $tmp = $path.'.tmp.'.bin2hex(random_bytes(4)); file_put_contents($tmp, $contents); rename($tmp, $path); }
}
